def _scaled(strokes: tuple[Stroke, ...], scale: float = 0.72, center=(500, 470), shift=(0, -15)) -> tuple[Stroke, ...]:
    result = []
    for stroke in strokes:
        points = tuple((
            center[0] + (x - center[0]) * scale + shift[0],
            center[1] + (y - center[1]) * scale + shift[1],
        ) for x, y in stroke.points)
        result.append(Stroke(points, stroke.width * 0.92, None if stroke.start_width is None else stroke.start_width * 0.92,
                             None if stroke.end_width is None else stroke.end_width * 0.92, stroke.cap))
    return tuple(result)


