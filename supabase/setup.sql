create or replace function public.set_song_tags(p_song_id uuid, p_tag_ids uuid[])
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not exists (
    select 1 from public.songs s
    where s.id = p_song_id
      and (
        (s.uploader_id = (select auth.uid()) and s.status = 'pending')
        or public.is_admin()
      )
  ) then
    raise exception 'Not allowed to update tags for this song';
  end if;

  if exists (
    select 1 from unnest(coalesce(p_tag_ids, array[]::uuid[])) requested(id)
    left join public.tags t on t.id = requested.id
    where t.id is null
  ) then
    raise exception 'Unknown tag id';
  end if;

  delete from public.song_tags where song_id = p_song_id;
  insert into public.song_tags (song_id, tag_id)
  select p_song_id, id
  from unnest(coalesce(p_tag_ids, array[]::uuid[])) requested(id)
  on conflict do nothing;
end;
$$;

revoke all on function public.set_song_tags(uuid, uuid[]) from public;
grant execute on function public.set_song_tags(uuid, uuid[]) to authenticated;

create or replace function public.replace_song_lyric_cues(p_song_id uuid, p_cues jsonb)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  inserted_count integer;
begin
  if not public.is_admin() then
    raise exception 'Administrator access required';
  end if;
  if not exists (select 1 from public.songs where id = p_song_id) then
    raise exception 'Song not found';
  end if;
  if jsonb_typeof(coalesce(p_cues, '[]'::jsonb)) <> 'array' then
    raise exception 'Cues must be a JSON array';
  end if;

  delete from public.lyric_cues where song_id = p_song_id;
  insert into public.lyric_cues (song_id, line_index, start_ms, end_ms, text)
  select p_song_id, cue.line_index, cue.start_ms, cue.end_ms, btrim(cue.text)
  from pg_catalog.jsonb_to_recordset(coalesce(p_cues, '[]'::jsonb))
    as cue(line_index integer, start_ms integer, end_ms integer, text text)
  order by cue.line_index;

  get diagnostics inserted_count = row_count;
  return inserted_count;
end;
$$;

revoke all on function public.replace_song_lyric_cues(uuid, jsonb) from public;
grant execute on function public.replace_song_lyric_cues(uuid, jsonb) to authenticated;

create or replace function public.delete_tag(p_tag_id uuid, p_confirm_used boolean default false)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  usage_count integer;
begin
  if not public.is_admin() then
    raise exception 'Administrator access required';
  end if;
  select count(*) into usage_count from public.song_tags where tag_id = p_tag_id;
  if usage_count > 0 and not p_confirm_used then
    raise exception 'Tag is used by % songs', usage_count;
  end if;
  delete from public.song_tags where tag_id = p_tag_id;
  delete from public.tags where id = p_tag_id;
  return usage_count;
end;
$$;

revoke all on function public.delete_tag(uuid, boolean) from public;
grant execute on function public.delete_tag(uuid, boolean) to authenticated;

