def scale(strokes: tuple[Stroke, ...], factor=0.72, center=(500, 470), shift=(0, -12)) -> tuple[Stroke, ...]:
    return tuple(Stroke(
        tuple((center[0] + (x-center[0])*factor + shift[0], center[1] + (y-center[1])*factor + shift[1]) for x, y in stroke.points),
        stroke.width * 0.92,
        None if stroke.start_width is None else stroke.start_width * 0.92,
        None if stroke.end_width is None else stroke.end_width * 0.92,
        stroke.cap,
    ) for stroke in strokes)


