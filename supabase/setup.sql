create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.admin_users
    where user_id = (select auth.uid())
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

create table if not exists public.songs (
  id uuid primary key default gen_random_uuid(),
  title text not null check (length(btrim(title)) between 1 and 160),
  artist text not null check (length(btrim(artist)) between 1 and 160),
  album text,
  release_year integer check (release_year between 1800 and 2100),
  language text,
  genre text,
  notes text,
  youtube_video_id text not null check (youtube_video_id ~ '^[A-Za-z0-9_-]{11}$'),
  pdf_path text not null unique,
  original_filename text not null,
  uploader_id uuid not null default auth.uid() references auth.users(id) on delete restrict,
  uploader_display_name text check (length(btrim(uploader_display_name)) between 1 and 120),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  reviewed_at timestamptz,
  reviewed_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.songs
  add column if not exists uploader_display_name text
  check (length(btrim(uploader_display_name)) between 1 and 120);

create table if not exists public.lyric_cues (
  id bigint generated by default as identity primary key,
  song_id uuid not null references public.songs(id) on delete cascade,
  line_index integer not null check (line_index >= 0),
  start_ms integer not null check (start_ms >= 0),
  end_ms integer check (end_ms is null or end_ms > start_ms),
  text text not null check (length(btrim(text)) > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (song_id, line_index)
);

create table if not exists public.tags (
  id uuid primary key default gen_random_uuid(),
  name text not null unique check (length(btrim(name)) between 1 and 80),
  slug text not null unique check (
    length(slug) between 1 and 80
    and slug = lower(slug)
    and slug !~ '\\s'
  ),
  created_at timestamptz not null default now()
);

create unique index if not exists tags_name_lower_unique_idx on public.tags (lower(name));

create table if not exists public.song_tags (
  song_id uuid not null references public.songs(id) on delete cascade,
  tag_id uuid not null references public.tags(id) on delete restrict,
  primary key (song_id, tag_id)
);

create index if not exists songs_status_created_idx on public.songs (status, created_at desc);
create index if not exists songs_uploader_status_idx on public.songs (uploader_id, status);
create index if not exists songs_title_lower_idx on public.songs (lower(title));
create index if not exists songs_artist_lower_idx on public.songs (lower(artist));
create index if not exists songs_language_idx on public.songs (language) where language is not null;
create index if not exists songs_genre_idx on public.songs (genre) where genre is not null;
create index if not exists songs_release_year_idx on public.songs (release_year desc) where release_year is not null;
create index if not exists lyric_cues_song_line_idx on public.lyric_cues (song_id, line_index);
create index if not exists lyric_cues_song_start_idx on public.lyric_cues (song_id, start_ms);
create index if not exists song_tags_tag_idx on public.song_tags (tag_id, song_id);

