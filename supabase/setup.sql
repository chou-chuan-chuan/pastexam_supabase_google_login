create or replace function public.set_song_uploader_display_name()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  user_metadata jsonb;
  app_metadata jsonb;
  resolved_name text;
begin
  select raw_user_meta_data, raw_app_meta_data
  into user_metadata, app_metadata
  from auth.users
  where id = new.uploader_id;

  if app_metadata ->> 'provider' = 'google'
     or app_metadata -> 'providers' @> '["google"]'::jsonb then
    resolved_name := coalesce(
      nullif(btrim(user_metadata ->> 'full_name'), ''),
      nullif(btrim(user_metadata ->> 'name'), ''),
      nullif(btrim(user_metadata ->> 'display_name'), '')
    );
  end if;

  resolved_name := coalesce(
    resolved_name,
    nullif(btrim(user_metadata ->> 'display_name'), ''),
    nullif(btrim(user_metadata ->> 'full_name'), ''),
    nullif(btrim(user_metadata ->> 'name'), ''),
    nullif(btrim(user_metadata ->> 'preferred_username'), ''),
    nullif(btrim(user_metadata ->> 'user_name'), ''),
    nullif(btrim(user_metadata ->> 'username'), ''),
    new.uploader_id::text
  );

  new.uploader_display_name := left(
    regexp_replace(resolved_name, '[[:cntrl:]]', '', 'g'),
    120
  );
  return new;
end;
$$;

